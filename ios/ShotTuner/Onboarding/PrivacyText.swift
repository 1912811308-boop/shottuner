二、各项权限的用途

本应用仅申请实现功能所必需的最小权限，每项权限的用途如下。你可以拒绝任一权限，拒绝后仅对应功能不可用，其余功能不受影响。

2.1 相机权限（CAMERA）

· 用途：用于本应用内建相机的实时取景与拍照。
· 处理方式：取景画面仅在设备内存中处理，用于计算曝光、构图与清晰度参考值。
· 是否留存：不自动留存。只有你主动按下快门时，照片才会保存到系统相册。
· 是否上传：不上传。

2.2 悬浮窗权限（SYSTEM_ALERT_WINDOW）

· 用途：当你使用"悬浮教练"功能、在系统相机中取景时，把一条拍摄建议以悬浮卡片的形式显示在屏幕上，让你不必切换应用就能看到提示。
· 显示内容：仅显示本应用生成的文字建议（例如"曝光偏低，可提高快门"）。
· 可关闭性：可在应用内一键关闭；关闭后不再显示任何悬浮内容。
· 不做的行为：不遮挡、不覆盖系统关键界面；不模拟点击；不诱导操作；不投放广告。

2.3 录屏权限（屏幕捕获，MediaProjection）

这是本应用最敏感的一项授权，我们在此逐条说明。

· 你为什么要授权：Android 系统不允许任何应用直接读取其他应用的相机取景画面。要在"系统相机"上方给建议，唯一合规的技术路径是：由你主动授权屏幕捕获，系统把当前屏幕的画面帧交给本应用，本应用据此分析构图与曝光。
· 我们读取什么：仅读取屏幕画面的像素数据，用于在本地计算亮度分布、边缘密度、人脸位置、画面倾斜度等统计量。
· 我们不做什么：
  - 不录制屏幕视频。本应用未使用任何视频编码或录制组件（未包含 MediaRecorder 等录制能力），技术上无法生成视频文件。
  - 不保存任何画面。屏幕帧只在内存中短暂存在，分析完成后立即丢弃，不写入任何文件、不进入相册、不进入缓存目录。
  - 不上传任何内容。本应用无网络权限，无法外传数据。
  - 不在后台静默运行。每次启动屏幕捕获都需要你通过系统弹窗明确确认（Android 14 及以上系统强制要求逐次确认）。
· 你如何随时停止：屏幕捕获运行期间，系统通知栏会常驻一条本应用的通知，点击即可立即停止；你也可以在应用内关闭悬浮教练，或直接强制停止本应用。
· 授权范围：授权仅对你确认的那一次会话有效，会话结束即失效。

2.4 前台服务权限（FOREGROUND_SERVICE / FOREGROUND_SERVICE_MEDIA_PROJECTION）

· 用途：在你使用悬浮教练期间，保证画面分析服务持续运行，并在通知栏显示"正在运行"的提示。
· 系统要求：Android 要求屏幕捕获类服务必须声明为前台服务并显示常驻通知，这是系统的强制规定，不是本应用的选择。
· 可停止性：通知提供停止入口。

2.5 通知权限（POST_NOTIFICATIONS）

· 用途：用于显示上述前台服务的常驻通知（内容是"悬浮教练正在运行，点击停止"）。
· 不用于：不发送营销信息、不发送推广通知、不发送任何与功能无关的提醒。
· 可拒绝：你可以拒绝该权限，拒绝后悬浮教练功能不可用，其余功能正常。

2.6 存储权限（WRITE_EXTERNAL_STORAGE，仅 Android 9 及以下）

· 用途：仅在 Android 9 及更低版本系统中，用于将你拍摄的照片保存到系统相册。
· Android 10 及以上：本应用通过系统媒体库接口写入相册，不再需要该权限，因此该权限已限定为仅在旧系统上申请。
· 范围：仅写入本应用拍摄的照片，不读取、不修改你设备上的其他任何文件。

2.7 震动权限（VIBRATE）

· 用途：在你完成一次构图或水平调整任务（例如把主体移到三分交点、把手机端平）时，触发一次约 15 毫秒的极短震动，作为"到位"的确认反馈。
· 性质：该权限为系统普通权限，安装时由系统自动授予，不会向你弹出任何授权请求，也不需要你进行任何操作。
