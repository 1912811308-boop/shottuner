4. 悬浮卡位置：你在屏幕上拖动悬浮卡后，其坐标位置会保存在本应用的本地配置中（SharedPreferences）。这是纯本机配置项，不含任何个人信息，保留期限为至你卸载本应用为止，卸载即清除。
5. 屏幕画面：不存在留存。屏幕帧只在内存中参与计算，分析完成后立即丢弃，不写入文件、不进入缓存目录、不进入相册，保留期限为零。

