四、数据的存储位置与保留期限

1. 存储位置：本应用没有服务器，没有云端存储，也不做任何数据同步。全应用涉及的全部数据只存在于你的手机本地。
2. 照片：你通过本应用拍摄的照片，由系统媒体库直接写入你手机的相册目录（Android 10 及以上为 Pictures/ShotTuner）。本应用不保留副本，也不维护自己的照片数据库。
